"""Dropdown tùy biến thay cho <select> và <input list>: tìm không dấu, phím, bấm ngoài, Escape trong hộp thoại, điện thoại."""
from common import *
with sync_playwright() as p:
    ctx, page, errs = new_ctx(p)
    page.goto(URL); page.wait_for_timeout(1200)
    page.click("#tab-prices"); page.wait_for_timeout(500)
    print("native ẩn:", page.evaluate("[...document.querySelectorAll('select')].map(s=>s.id+':'+s.classList.contains('xs-native')+':'+!!s._xs)"))
    # Mở lọc nhóm, gõ tìm không dấu, Enter chọn
    page.click("#pe-group + .xs-btn"); page.wait_for_timeout(300)
    page.screenshot(path=f"{SHOT}/95_dd_open.png")
    page.keyboard.type("bat huong"); page.wait_for_timeout(200)
    print("kết quả tìm:", page.eval_on_selector_all(".xs-opt", "els=>els.map(e=>e.textContent)"))
    page.screenshot(path=f"{SHOT}/95_dd_search.png")
    page.keyboard.press("Enter"); page.wait_for_timeout(400)
    print("đã lọc:", page.evaluate("[S.peFilter.group, document.querySelector('#pe-group + .xs-btn').title, !!document.querySelector('.xs-pop')]"))
    # Phím mũi tên trên dropdown ít lựa chọn (không có ô tìm)
    page.focus("#pe-status + .xs-btn"); page.keyboard.press("ArrowDown"); page.wait_for_timeout(250)
    page.keyboard.press("ArrowDown"); page.keyboard.press("Enter"); page.wait_for_timeout(400)
    print("trạng thái:", page.evaluate("S.peFilter.status"))
    # Bấm ra ngoài thì đóng
    page.click("#pe-glaze + .xs-btn"); page.wait_for_timeout(250); page.mouse.click(700, 80); page.wait_for_timeout(300)
    print("đóng khi bấm ngoài:", page.locator(".xs-pop").count())
    # Escape trong hộp thoại: chỉ đóng dropdown, không đóng hộp thoại
    page.click("[data-act=clear-filter]"); page.wait_for_timeout(300)
    page.click("[data-act=bulk]"); page.wait_for_timeout(300)
    page.click("#bk-round + .xs-btn"); page.wait_for_timeout(300)
    page.screenshot(path=f"{SHOT}/95_dd_modal.png")
    page.keyboard.press("Escape"); page.wait_for_timeout(250)
    print("Escape:", page.locator(".xs-pop").count(), page.locator(".modal").count())
    page.click(".modal [data-close] >> nth=0"); page.wait_for_timeout(200)
    # Ô gợi ý (datalist) trong hộp thêm sản phẩm
    page.click("[data-act=add]"); page.wait_for_timeout(300)
    page.click("#pf-group"); page.wait_for_timeout(250)
    print("gợi ý tất cả:", page.locator(".xs-opt").count())
    page.keyboard.type("den"); page.wait_for_timeout(250)
    print("gợi ý 'den':", page.eval_on_selector_all(".xs-opt", "els=>els.map(e=>e.textContent)"))
    page.screenshot(path=f"{SHOT}/95_dd_combo.png")
    page.locator(".xs-opt").first.click(); page.wait_for_timeout(200)
    print("chọn gợi ý:", page.input_value("#pf-group"), page.locator(".xs-pop").count())
    page.click(".modal [data-close] >> nth=0"); page.wait_for_timeout(200)
    # Điện thoại
    page.set_viewport_size({"width": 390, "height": 844}); page.wait_for_timeout(300)
    page.click("#pe-group + .xs-btn"); page.wait_for_timeout(300)
    page.screenshot(path=f"{SHOT}/95_dd_mobile.png")
    print("tràn ngang:", page.evaluate("document.documentElement.scrollWidth > innerWidth"))
    page.emulate_media(color_scheme="dark"); page.wait_for_timeout(200)
    page.screenshot(path=f"{SHOT}/95_dd_mobile_dark.png")
    # Nạp thẳng data/pdf_data.json: chỉ thay bảng giá, giữ mẫu và báo giá
    page.set_viewport_size({"width": 1440, "height": 900}); page.emulate_media(color_scheme="light")
    nrec = page.evaluate("S.records.size")
    page.click("#tab-data"); page.wait_for_timeout(300)
    page.click("#view-data [data-act=restore]"); page.set_input_files("#file-any", os.path.join(DATA, "pdf_data.json")); page.wait_for_timeout(400)
    page.click(".modal-f button:has-text('Thay thế bảng giá')"); page.wait_for_timeout(1500)
    print("nạp pdf_data.json:", page.evaluate("[S.products.size, S.records.size]"), "mẫu/báo giá trước:", nrec, toasts(page)[-1:])
    print("errs:", errs)
    ctx.close()
