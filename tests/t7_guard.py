from common import *
with sync_playwright() as p:
    ctx, page, errs = new_ctx(p)
    page.goto(URL); page.wait_for_timeout(900)
    page.click("#tab-prices"); page.wait_for_timeout(300)
    # Thêm sản phẩm: một hộp thoại tạo nhiều dòng men cùng lúc
    page.click("[data-act=add]"); page.wait_for_timeout(200)
    page.fill("#pf-name", "Tam cấp gỗ thử"); page.fill("#pf-group", "Tam cấp/kệ bát hương"); page.fill("#pf-unit", "bộ")
    page.fill("[data-gp='0']", "0")
    page.click(".modal [data-ok]"); page.wait_for_timeout(200)
    print("giá 0:", page.text_content("#pf-err"))
    page.fill("[data-gp='0']", "1,500,000"); page.locator("[data-g='1']").uncheck()
    page.click(".modal [data-ok]"); page.wait_for_timeout(500)
    added = page.evaluate("[...S.products.values()].filter(p=>p.name==='Tam cấp gỗ thử').map(p=>[p.code,p.glaze,p.price,p.unit])")
    print("đã thêm:", added)
    code = added[0][0]
    # Thêm trùng → báo lỗi, không tạo mã mới
    page.click("[data-act=add]"); page.wait_for_timeout(200)
    page.fill("#pf-name", "Tam cấp gỗ thử"); page.fill("#pf-group", "Tam cấp/kệ bát hương"); page.locator("[data-g='1']").uncheck()
    page.click(".modal [data-ok]"); page.wait_for_timeout(200)
    print("trùng:", page.text_content("#pf-err"))
    page.click(".modal [data-close] >> nth=0")
    page.screenshot(path=f"{SHOT}/40_prices_new.png")
    # Sửa giá trong bảng rồi rời trang → hộp nhắc
    page.fill("#pe-q", "Tam cấp gỗ thử"); page.wait_for_timeout(500)
    page.fill(f"input[data-k='{code}'][data-f=price]", "abc")
    print("lỗi giá:", page.evaluate(f"S.pe.err.get('{code}')"), page.is_disabled("[data-act=save]"))
    page.fill(f"input[data-k='{code}'][data-f=price]", "1.600.000")
    page.click("#tab-builder"); page.wait_for_timeout(300)
    print("hộp nhắc:", page.inner_text(".modal-h"))
    page.click(".modal-f button:has-text('Ở lại')"); page.wait_for_timeout(200)
    print("vẫn ở:", page.evaluate("S.view"))
    page.click("#tab-builder"); page.click(".modal-f button:has-text('Lưu thay đổi')"); page.wait_for_timeout(600)
    print("đã lưu & chuyển:", page.evaluate(f"[S.view, S.products.get('{code}').price]"))
    # Điều chỉnh hàng loạt: +10%, làm tròn 10.000, chỉ đổi trong bảng đến khi bấm Lưu
    page.click("#tab-prices"); page.wait_for_timeout(300)
    page.fill("#pe-q", "Tam cấp gỗ thử"); page.wait_for_timeout(500)
    page.click("[data-act=bulk]"); page.fill("#bk-val", "10"); page.wait_for_timeout(300)
    page.click(".modal [data-ok]"); page.wait_for_timeout(200)
    print("hàng loạt:", page.evaluate(f"[S.pe.rows.get('{code}').price, S.products.get('{code}').price]"))
    page.click("[data-act=save]"); page.wait_for_timeout(500)
    print("sau lưu:", page.evaluate(f"S.products.get('{code}').price"))
    # Ngừng dùng → ẩn khỏi danh mục
    page.fill("#pe-q", "Tam cấp gỗ thử"); page.wait_for_timeout(500)
    page.click("[data-act=toggle]"); page.click("[data-act=save]"); page.wait_for_timeout(500)
    page.click("#tab-builder"); page.wait_for_timeout(300)
    page.fill("#cat-q", "Tam cấp gỗ"); page.wait_for_timeout(400)
    print("ẩn khỏi danh mục:", page.locator(".pcard").count())
    # Xóa sản phẩm
    page.click("#tab-prices"); page.wait_for_timeout(300)
    page.select_option("#pe-status", "all"); page.fill("#pe-q", "Tam cấp gỗ thử"); page.wait_for_timeout(500)
    page.locator(f"tr[data-k='{code}'] .pname").click(); page.wait_for_timeout(200)
    page.click(".modal [data-del]"); page.click(".modal-f button:has-text('Xóa vĩnh viễn')"); page.wait_for_timeout(500)
    print("đã xóa:", page.evaluate(f"S.products.has('{code}')"))
    page.select_option("#pe-status", "active")
    print("errs:", errs)
    ctx.close()
